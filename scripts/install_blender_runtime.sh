#!/usr/bin/env bash
# Install the BlenderLore Harbor runtime on Debian/Ubuntu Linux.
#
# Installs:
#   Blender 5.1.2 (including Blender Python, EEVEE and Cycles)
#   FFmpeg and FFprobe
#
# Usage:
#   sudo ./scripts/install_blender_runtime.sh
#   sudo ./scripts/install_blender_runtime.sh --prefix /opt/blender
#
# The script writes a shell fragment to <prefix>/blenderlore-env.sh. Source it
# before starting Harbor, or copy these variables into the Harbor image.
set -Eeuo pipefail

readonly BLENDER_VERSION="5.1.2"
readonly BLENDER_MAJOR="5.1"
PREFIX="/opt/blender"
SKIP_APT=0

usage() {
  sed -n '2,14p' "$0"
}

while (($#)); do
  case "$1" in
    --prefix)
      [[ $# -ge 2 ]] || { echo "--prefix requires a path" >&2; exit 2; }
      PREFIX="$2"
      shift 2
      ;;
    --skip-apt)
      SKIP_APT=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

[[ "$(uname -s)" == "Linux" ]] || { echo "This installer targets Linux Harbor environments." >&2; exit 1; }
[[ "$(uname -m)" == "x86_64" ]] || { echo "Only Linux x86_64 is supported by this installer." >&2; exit 1; }
command -v curl >/dev/null || { echo "curl is required" >&2; exit 1; }
command -v sha256sum >/dev/null || { echo "sha256sum is required" >&2; exit 1; }

if ((SKIP_APT == 0)); then
  command -v apt-get >/dev/null || { echo "apt-get not found; use --skip-apt" >&2; exit 1; }
  apt-get update
  DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends ffmpeg ca-certificates xz-utils tar
fi

mkdir -p "$PREFIX"
archive="/tmp/blender-${BLENDER_VERSION}-linux-x64.tar.xz"
url="https://download.blender.org/release/Blender${BLENDER_MAJOR}/blender-${BLENDER_VERSION}-linux-x64.tar.xz"

echo "Downloading Blender ${BLENDER_VERSION}..."
curl --fail --location --retry 3 --output "$archive" "$url"

install_dir="$PREFIX/blender-${BLENDER_VERSION}"
rm -rf "$install_dir"
mkdir -p "$install_dir"
tar -xJf "$archive" --strip-components=1 -C "$install_dir"
ln -sfn "$install_dir" "$PREFIX/current"

blender_bin="$PREFIX/current/blender"
[[ -x "$blender_bin" ]] || { echo "Blender executable was not installed" >&2; exit 1; }
version_output="$($blender_bin --version 2>&1)"
grep -F "Blender ${BLENDER_VERSION}" <<<"$version_output" >/dev/null || {
  echo "Unexpected Blender version:" >&2
  echo "$version_output" >&2
  exit 1
}

ffmpeg_bin="$(command -v ffmpeg)"
ffprobe_bin="$(command -v ffprobe)"
cat > "$PREFIX/blenderlore-env.sh" <<EOF
# Generated by install_blender_runtime.sh
export BLENDERLORE_BLENDER_BIN="$blender_bin"
export BLENDERLORE_FFMPEG_BIN="$ffmpeg_bin"
export BLENDERLORE_FFPROBE_BIN="$ffprobe_bin"
export PATH="$PREFIX/current:\$PATH"
EOF
chmod 0644 "$PREFIX/blenderlore-env.sh"

echo "Runtime installed successfully."
echo "Blender: $blender_bin"
echo "FFmpeg:  $ffmpeg_bin"
echo "FFprobe: $ffprobe_bin"
echo "Source:  $PREFIX/blenderlore-env.sh"
